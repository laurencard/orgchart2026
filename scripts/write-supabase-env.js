const fs = require("fs");
const path = require("path");

const url = process.env.SUPABASE_URL || "";
const anonKey = process.env.SUPABASE_ANON_KEY || "";
const outPath = path.join(__dirname, "..", "env.local.js");

const payload = { url, anonKey };
const body = `// Generated by npm run build. Set SUPABASE_URL and SUPABASE_ANON_KEY (Vercel project env or shell).\nwindow.__NFTY_SUPABASE__ = ${JSON.stringify(payload)};\n`;

fs.writeFileSync(outPath, body, "utf8");
if (url && anonKey) {
  console.log("Wrote env.local.js with Supabase URL + anon key.");
} else {
  console.log("Wrote env.local.js (empty Supabase config — app uses local storage only).");
}
